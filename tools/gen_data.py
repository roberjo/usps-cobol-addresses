#!/usr/bin/env python3
"""Generate deterministic seed data and an edit-transaction file for EBUPD01.

Outputs (defaults):
  db/seed.sql            ams_route + ams_address rows (PostgreSQL COPY format)
  data/in/ebtrans.dat    80-byte fixed EBTRANS records, no line terminators

Everything is driven by a fixed seed, so reruns produce byte-identical files
and the golden regression outputs stay stable. The ZIP codes are in the
unassigned 000xx range on purpose: none of this is real address data.

Usage:
  python tools/gen_data.py                 # ASCII transactions (what the job reads)
  python tools/gen_data.py --ebcdic -t data/in/ebtrans.ebc   # host-format copy
"""
from __future__ import annotations

import argparse
import random
from dataclasses import dataclass, field
from pathlib import Path

from faker import Faker

from ebcdic import EBTRANS_LAYOUT, pack_comp3, encode_record

SEED = 20261005
RUNDATE = "20261005"
ZIPS = ["00011", "00012", "00013"]
ROUTES = ["C001", "C002", "C003", "C004", "C005", "C006", "R001", "R002"]
# Edit books "returned by carriers" this cycle: only these routes get transactions.
EDIT_ROUTES = [("00011", "C002"), ("00011", "R001"), ("00012", "C001"),
               ("00012", "C005"), ("00013", "C003")]


@dataclass
class Addr:
    seq: int
    primary: str
    street: str
    unit: str | None
    zip4: str | None


@dataclass
class Route:
    zip5: str
    route_id: str
    addrs: list[Addr] = field(default_factory=list)


def street_names(fake: Faker, n: int) -> list[str]:
    names: list[str] = []
    while len(names) < n:
        s = f"{fake.street_name()}".upper()
        if len(s) <= 28 and s not in names and s.isascii():
            names.append(s)
    return names


def build_routes(rng: random.Random, fake: Faker) -> list[Route]:
    routes = []
    for zip5 in ZIPS:
        for route_id in ROUTES:
            r = Route(zip5, route_id)
            target = rng.randint(150, 400)
            streets = street_names(fake, rng.randint(4, 9))
            seq = 0
            while len(r.addrs) < target:
                street = rng.choice(streets)
                start = rng.randrange(100, 9000, 2)
                for side in (0, 1):  # even side up, odd side back down
                    nums = [start + side + 2 * i for i in range(rng.randint(3, 12))]
                    if side:
                        nums.reverse()
                    for num in nums:
                        zip4 = f"{rng.randint(1, 9999):04d}" if rng.random() < 0.9 else None
                        if route_id.startswith("C") and rng.random() < 0.06:
                            for u in range(1, rng.randint(2, 8)):
                                seq += 1
                                r.addrs.append(Addr(seq, str(num), street, f"APT {u}", zip4))
                        else:
                            seq += 1
                            r.addrs.append(Addr(seq, str(num), street, None, zip4))
                        if len(r.addrs) >= target:
                            break
                    if len(r.addrs) >= target:
                        break
            routes.append(r)
    return routes


def copy_val(v: str | None) -> str:
    return "\\N" if v is None else v


def write_seed(routes: list[Route], path: Path) -> None:
    lines = [
        "-- Generated by tools/gen_data.py -- do not edit by hand.",
        "BEGIN;",
        "TRUNCATE ams_address, ams_route, eb_checkpoint RESTART IDENTITY;",
        "COPY ams_route (zip5, route_id, route_type) FROM stdin;",
    ]
    for r in routes:
        lines.append(f"{r.zip5}\t{r.route_id}\t{r.route_id[0]}")
    lines += ["\\.", "COPY ams_address (zip5, zip4, route_id, dlvy_seq, primary_nbr, "
              "street_name, unit, status_cd) FROM stdin;"]
    for r in routes:
        for a in r.addrs:
            lines.append("\t".join([r.zip5, copy_val(a.zip4), r.route_id, str(a.seq),
                                    a.primary, a.street, copy_val(a.unit), "A"]))
    lines += ["\\.", "COMMIT;", ""]
    path.write_text("\n".join(lines))


def tx(action: str, zip5: str, route: str, seq, primary: str = "", street: str = "",
       unit: str | None = None, zip4: str | None = None, carrier: str = "",
       date: str = "") -> dict:
    return dict(action=action, zip5=zip5, route=route, seq=seq, primary=primary,
                street=street, unit=unit or "", zip4=zip4 or "", carrier=carrier,
                date=date)


def build_transactions(rng: random.Random, fake: Faker, routes: list[Route]) -> list[dict]:
    by_key = {(r.zip5, r.route_id): r for r in routes}
    txs: list[dict] = []

    def edit_date() -> str:
        return f"202609{rng.randint(1, 30):02d}"

    used_by_route: dict[tuple[str, str], set[int]] = {}
    for key in EDIT_ROUTES:
        r = by_key[key]
        carrier = f"{rng.randint(10000, 99999)}{r.route_id[0]}"
        new_streets = street_names(fake, 2)
        used = used_by_route.setdefault(key, set())

        def pick() -> Addr:
            while True:
                a = rng.choice(r.addrs)
                if a.seq not in used:
                    used.add(a.seq)
                    return a

        for _ in range(rng.randint(8, 14)):  # vacated / demolished
            a = pick()
            txs.append(tx("D", r.zip5, r.route_id, a.seq, a.primary, a.street,
                          a.unit, a.zip4, carrier, edit_date()))
        for _ in range(rng.randint(8, 14)):  # unit splits, ZIP+4 corrections
            a = pick()
            unit = a.unit if rng.random() < 0.5 else f"UNIT {rng.choice('ABCD')}"
            zip4 = f"{rng.randint(1, 9999):04d}"
            txs.append(tx("C", r.zip5, r.route_id, a.seq, a.primary, a.street,
                          unit, zip4, carrier, edit_date()))
        for _ in range(rng.randint(10, 18)):  # new construction, inserted mid-route
            pos = rng.randint(1, len(r.addrs) + 1)
            num = str(rng.randrange(10001, 19999, 2))
            txs.append(tx("A", r.zip5, r.route_id, pos, num, rng.choice(new_streets),
                          None, f"{rng.randint(1, 9999):04d}", carrier, edit_date()))
        # delete then re-add at the same position (sequence freed by the delete)
        a = pick()
        txs.append(tx("D", r.zip5, r.route_id, a.seq, a.primary, a.street, a.unit,
                      a.zip4, carrier, edit_date()))
        txs.append(tx("A", r.zip5, r.route_id, a.seq, str(int(a.primary) + 1000),
                      a.street, None, a.zip4, carrier, edit_date()))

    good = len(txs)
    r = by_key[EDIT_ROUTES[0]]
    untouched = [x for x in r.addrs if x.seq not in used_by_route[EDIT_ROUTES[0]]]
    a, m = untouched[10], untouched[40]
    z, rt, c, d = r.zip5, r.route_id, "12345C", "20260915"
    bad = [
        # validation rejects (EBVALID)
        tx("X", z, rt, 5, "100", "ELM ST", carrier=c, date=d),              # 01 action
        tx("U", z, rt, 5, "100", "ELM ST", carrier=c, date=d),              # 01 action
        tx("A", "0A011", rt, 5, "100", "ELM ST", carrier=c, date=d),        # 02 zip5
        tx("A", "     ", rt, 5, "100", "ELM ST", carrier=c, date=d),        # 02 zip5
        tx("C", z, rt, 7, "100", "ELM ST", zip4="12B4", carrier=c, date=d), # 03 zip4
        tx("A", z, rt, 9, "100", "", carrier=c, date=d),                    # 04 street
        tx("A", z, rt, 9, "", "ELM ST", carrier=c, date=d),                 # 04 primary
        tx("D", z, rt, 9, "", "", carrier=c, date=d),                       # 04 primary
        tx("A", z, rt, 9, "100", "ELM ST", carrier="", date=d),             # 04 carrier
        tx("A", z, rt, 9, "100", "ELM ST", carrier=c, date="20261341"),     # 05 bad date
        tx("A", z, rt, 9, "100", "ELM ST", carrier=c, date="2026SEPT"),     # 05 bad date
        tx("A", z, rt, 9, "100", "ELM ST", carrier=c, date="20261006"),     # 06 future
        tx("A", z, "C099", 9, "100", "ELM ST", carrier=c, date=d),          # 07 route
        tx("A", "00019", rt, 9, "100", "ELM ST", carrier=c, date=d),        # 07 route
        tx("A", z, rt, b"    ", "100", "ELM ST", carrier=c, date=d),        # 08 S0C7 bait
        tx("A", z, rt, 0, "100", "ELM ST", carrier=c, date=d),              # 08 zero seq
        tx("A", z, rt, -4, "100", "ELM ST", carrier=c, date=d),             # 08 negative
        tx("A", z, rt, 9, "100", "\x00" * 28, carrier=c, date=d),           # 09 low-values
        tx("C", z, rt, 9, "100", "ELM\xffST", carrier=c, date=d),           # 09 high-values
        # update rejects (EBUPDT)
        tx("D", z, rt, 9000, "100", "ELM ST", carrier=c, date=d),           # 10 not found
        tx("C", z, rt, 9001, "100", "ELM ST", carrier=c, date=d),           # 10 not found
        tx("A", z, rt, 3, a.primary, a.street, a.unit, a.zip4, c, d),       # 11 duplicate
        tx("D", z, rt, m.seq, "99999", m.street, carrier=c, date=d),          # 12 mismatch
    ]
    txs += bad
    rng.shuffle(txs)  # carriers return books in no particular order
    print(f"transactions: {len(txs)} ({good} well-formed, {len(bad)} planted bad)")
    return txs


def to_record(t: dict) -> bytes:
    values = {
        "EBT-ACTION-CD": t["action"], "EBT-ZIP5": t["zip5"], "EBT-ROUTE-ID": t["route"],
        "EBT-DLVY-SEQ": t["seq"], "EBT-PRIMARY-NBR": t["primary"],
        "EBT-STREET-NAME": t["street"], "EBT-UNIT": t["unit"], "EBT-ZIP4": t["zip4"],
        "EBT-CARRIER-ID": t["carrier"], "EBT-EDIT-DATE": t["date"], "FILLER": "",
    }
    out = bytearray()
    for name, length, kind in EBTRANS_LAYOUT:
        v = values[name]
        if kind == "comp3":
            out += v if isinstance(v, bytes) else pack_comp3(v, length)
        else:
            out += v.encode("latin-1").ljust(length, b" ")[:length]
    assert len(out) == 80
    return bytes(out)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("-s", "--seed-sql", type=Path, default=Path("db/seed.sql"))
    ap.add_argument("-t", "--trans", type=Path, default=Path("data/in/ebtrans.dat"))
    ap.add_argument("--ebcdic", action="store_true",
                    help="encode text fields as EBCDIC (cp037); COMP-3 bytes untouched")
    args = ap.parse_args()

    rng = random.Random(SEED)
    fake = Faker("en_US")
    fake.seed_instance(SEED)

    routes = build_routes(rng, fake)
    txs = build_transactions(rng, fake, routes)

    args.seed_sql.parent.mkdir(parents=True, exist_ok=True)
    args.trans.parent.mkdir(parents=True, exist_ok=True)
    write_seed(routes, args.seed_sql)
    recs = [to_record(t) for t in txs]
    if args.ebcdic:
        recs = [encode_record(r, EBTRANS_LAYOUT) for r in recs]
    args.trans.write_bytes(b"".join(recs))
    print(f"routes: {len(routes)}, addresses: {sum(len(r.addrs) for r in routes)}")
    print(f"wrote {args.seed_sql} and {args.trans} ({'EBCDIC' if args.ebcdic else 'ASCII'})")


if __name__ == "__main__":
    main()
